from pathlib import Path
import joblib
import pandas as pd

MODEL = Path(__file__).parent / "artifacts" / "fertilizer_pipeline.joblib"


def expert_fertilizer_rule(data):
    crop = (data.get("crop") or "Paddy").strip().title()
    soil_type = (data.get("soil_type") or data.get("soil_color") or "Loamy").strip().title()
    soil_color = (data.get("soil_color") or "Loamy").strip().title()
    moisture = float(data.get("moisture") or 55.0)
    water = float(data.get("water_availability") or 70.0)

    # Base recommendation logic
    if "Paddy" in crop or "Rice" in crop:
        fertilizer = "Urea (Neem Coated) + DAP + Zinc Sulphate (25kg/ha)"
        explanation = f"Paddy in {soil_type} soil ({soil_color}) requires high Nitrogen & Zinc. Apply DAP basal dose followed by Neem-coated Urea split top-dressing."
        score = 88.0
    elif "Maize" in crop or "Corn" in crop:
        fertilizer = "NPK 20:20:0:13 (Ammonium Phosphate Sulphate) + Urea"
        explanation = f"Maize responds strongly to Nitrogen and Sulphur in {soil_type} soil. Apply NPK 20:20:0:13 at sowing and Urea at knee-high stage."
        score = 85.0
    elif "Cotton" in crop:
        fertilizer = "NPK 10:26:26 + Magnesium Sulphate"
        explanation = f"Cotton in {soil_color} ({soil_type}) soil needs balanced Phosphorus and Potash to strengthen bolls and prevent leaf reddening."
        score = 84.0
    elif "Areca" in crop or "Nut" in crop:
        fertilizer = "NPK 15:15:15 + Organic Vermicompost (10kg/tree)"
        explanation = f"Areca nut palms in {soil_type} soil thrive on organic matter combined with equal ratio NPK applied in two split doses post-monsoon."
        score = 87.0
    elif "Groundnut" in crop or "Peanut" in crop:
        fertilizer = "Single Super Phosphate (SSP) + Gypsum (400kg/ha)"
        explanation = f"Groundnut requires Sulphur & Calcium from SSP and Gypsum for optimum pod filling and oil content in {soil_type} soil."
        score = 86.0
    elif "Vegetable" in crop or "Tomato" in crop or "Onion" in crop:
        fertilizer = "Water-soluble NPK 19:19:19 + Micronutrient Mix"
        explanation = f"Vegetable crops in {soil_type} soil require frequent fertigation of water-soluble NPK 19:19:19 for uniform growth and high yield."
        score = 89.0
    else:
        if "Black" in soil_color or "Black" in soil_type:
            fertilizer = "DAP (50kg/acre) + Muriate of Potash (MOP)"
            explanation = "Black clay soil has high moisture retention. Apply DAP and Potash basal dose prior to sowing."
            score = 82.0
        elif "Red" in soil_color or "Laterite" in soil_color:
            fertilizer = "NPK 19:19:19 + Organic Compost (2 tons/acre)"
            explanation = "Red/Laterite soils are prone to leaching and acidity. Combine NPK with organic compost to improve cation exchange capacity."
            score = 80.0
        else:
            fertilizer = "Urea + DAP + NPK 14:35:14"
            explanation = f"Balanced NPK application suitable for general field crops in {soil_type} soil conditions."
            score = 83.0

    if moisture < 40:
        score -= 5.0
        explanation += " Note: Soil moisture is low; ensure irrigation before fertilizer application."
    if water >= 60:
        score += 5.0

    return {
        "predicted_fertilizer": fertilizer,
        "suitability_score": round(max(50.0, min(98.0, score)), 1),
        "model_used": False,
        "explanation": explanation,
    }


def recommend(data):
    if MODEL.exists():
        try:
            pipeline = joblib.load(MODEL)
            x = pd.DataFrame([{
                "location": data.get("location", "Shivamogga"),
                "crop": data.get("crop", "Paddy"),
                "soil_type": data.get("soil_type", "Loamy"),
                "soil_color": data.get("soil_color", "Loamy"),
                "moisture": float(data.get("moisture", 55)),
                "water_availability": float(data.get("water_availability", 70)),
                "previous_crop": data.get("previous_crop", "Unknown"),
                "previous_yield": float(data.get("previous_yield", 0)),
            }])
            prediction = pipeline.predict(x)[0]
            if prediction and str(prediction).strip() and str(prediction) != "None":
                score = 85.0
                if hasattr(pipeline, "predict_proba"):
                    try:
                        score = float(max(pipeline.predict_proba(x)[0]) * 100)
                    except Exception:
                        pass
                return {
                    "predicted_fertilizer": str(prediction),
                    "suitability_score": round(score, 1),
                    "model_used": True,
                    "explanation": f"Prediction generated by trained ML fertilizer pipeline for {data.get('crop')} in {data.get('soil_type')} soil.",
                }
        except Exception as e:
            print("ML Fertilizer pipeline execution note:", e)

    return expert_fertilizer_rule(data)

