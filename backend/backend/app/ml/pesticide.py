from pathlib import Path
import joblib
import pandas as pd

MODEL = Path(__file__).parent / "artifacts" / "pesticide_pipeline.joblib"


def expert_pesticide_rule(data):
    crop = (data.get("crop") or "Paddy").strip().title()
    pest = (data.get("pest") or "Unknown").strip().title()
    age = int(data.get("crop_age_days") or 15)
    temp = float(data.get("temperature") or 28.0)
    humidity = float(data.get("humidity") or 75.0)
    rain = float(data.get("rainfall") or 0.0)

    # Compute risk score based on humidity, temperature & rain
    pressure = 20.0
    if humidity > 70:
        pressure += (humidity - 70) * 1.2
    if rain > 5.0:
        pressure += 15.0
    if 24.0 <= temp <= 32.0:
        pressure += 10.0
    pressure = min(98.0, max(15.0, pressure))

    # Match pesticide product based on crop, pest, weather
    if "Fungus" in pest or "Blight" in pest or "Rot" in pest or humidity > 80 or rain > 10:
        pesticide = "Mancozeb 75% WP / Copper Oxychloride 50% WP (Fungicide)"
        explanation = f"High humidity ({humidity}%) and moisture create high fungal blast/blight risk for {crop}. Apply Mancozeb 75% WP spray (2g/L water) as protective coat."
    elif "Borer" in pest or "Worm" in pest or "Caterpillar" in pest or "Maize" in crop:
        pesticide = "Emamectin Benzoate 5% SG / Chlorpyrifos 20% EC"
        explanation = f"Stem borer / Fall armyworm risk detected for {crop} (Age: {age} days). Spray Emamectin Benzoate 5% SG (0.4g/L) during cool morning or evening hours."
    elif "Sucking" in pest or "Aphid" in pest or "Whitefly" in pest or "Thrips" in pest:
        pesticide = "Imidacloprid 17.8% SL / Thiamethoxam 25% WG"
        explanation = f"Warm temperatures ({temp}°C) favour sucking pest outbreaks. Apply Imidacloprid 17.8% SL (0.5ml/L) systemic insecticide."
    elif age <= 20:
        pesticide = "Neem-based Bio Pesticide (Azadirachtin 10,000 ppm)"
        explanation = f"Young crop stage ({age} days). Use eco-friendly Neem bio-pesticide (3ml/L) for early preventive defense without leaf burn risk."
    else:
        pesticide = "Neem Bio-Pesticide + Chlorpyrifos 20% EC (Broad Spectrum)"
        explanation = f"General pest defense for {crop} at {age} days age under current temperature {temp}°C & humidity {humidity}%."

    return {
        "predicted_pesticide": pesticide,
        "pest_pressure_score": round(pressure, 1),
        "model_used": False,
        "explanation": explanation,
    }


def recommend(data):
    if MODEL.exists():
        try:
            pipeline = joblib.load(MODEL)
            x = pd.DataFrame([{
                "location": data.get("location", "Shivamogga"),
                "crop": data.get("crop", "Paddy"),
                "crop_age_days": int(data.get("crop_age_days", 20)),
                "pest": data.get("pest", "Unknown"),
                "temperature": float(data.get("temperature", 28.0)),
                "humidity": float(data.get("humidity", 70.0)),
                "rainfall": float(data.get("rainfall", 0.0)),
                "sunlight": float(data.get("sunlight", 7.0)),
                "observed_severity": float(data.get("observed_severity", 50.0)),
            }])
            prediction = str(pipeline.predict(x)[0]).strip()
            if prediction and prediction != "None":
                name_map = {
                    "ValidatedPesticideA": "Neem-based Bio Pesticide (Azadirachtin 10,000 ppm)",
                    "ValidatedPesticideB": "Chlorpyrifos 20% EC (Termite & Stem Borer Control)",
                    "ValidatedPesticideC": "Mancozeb 75% WP (Fungicide & Blight Control)",
                    "ValidatedPesticideD": "Imidacloprid 17.8% SL (Sucking Pest Control)",
                }
                final_name = name_map.get(prediction, prediction)
                return {
                    "predicted_pesticide": final_name,
                    "pest_pressure_score": float(data.get("observed_severity", 50.0)),
                    "model_used": True,
                    "explanation": f"Prediction generated by trained ML pesticide model for {data.get('crop')}.",
                }

        except Exception as e:
            print("ML Pesticide pipeline execution note:", e)

    return expert_pesticide_rule(data)

